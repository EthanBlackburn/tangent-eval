#!/usr/bin/env python3
"""The benchmark's table: every entrant's runs as the measures bench/README.md defines.

    python3 -I bench/score.py [--json OUT.json] > bench/LEADERBOARD.md

Reads bench/entrants.json: an entrant is a pairing of models behind the pipeline, or a rule set; a run is the
score_v2.py output of its first pass (`judge`) and, for a pairing, of what stood after review (`reviewed`), with
the fees and the reviewer's failures as they were recorded. Every figure is counted from those files; nothing is
judged by a model. Standard library only."""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
TECHNIQUES = 35  # Stratus techniques in the corpus, each run from a new address and from the member's usual place


def read(path):
    """One score_v2.py output as the benchmark's counts."""
    t = open(os.path.join(ROOT, path)).read()
    n = lambda pat: int(re.search(pat, t)[1])
    names = lambda label: set(m[1].split(", ")) if (m := re.search(rf"\n   {label}: (.+)", t)) else set()
    s = {"judged": n(r"judged (\d+) records"), "not_judged": n(r"judged \d+ records, (\d+) not judged"),
         "ordinary": n(r"ordinary: (\d+) of"), "ordinary_of": n(r"ordinary: \d+ of (\d+)"),
         "dev_caught": n(r"\n   ours: (\d+)/"), "dev_flagged": n(r"\n   ours \(negatives\): (\d+)/")}
    for place in ("away", "usual"):
        missed, flagged = names(f"missed, stratus {place}"), names(f"flagged, control {place}")
        s[place] = {"attacks": n(rf"\n   stratus {place}: (\d+)/"), "controls": n(rf"\n   control {place}: (\d+)/"),
                    # a pair told apart: the technique flagged, the harmless calls beside it left alone
                    "apart": TECHNIQUES - len(missed | flagged)}
        assert s[place]["attacks"] == TECHNIQUES - len(missed) and s[place]["controls"] == len(flagged), path
    return s


def span(values, fmt="{}"):
    values = [v for v in values if v is not None]
    if not values:
        return "not recorded"
    lo, hi = min(values), max(values)
    return fmt.format(lo) if lo == hi else f"{fmt.format(lo)}–{fmt.format(hi)}"


args = sys.argv[1:]
out = args[args.index("--json") + 1] if "--json" in args else None
rows = []
for e in json.load(open(os.path.join(HERE, "entrants.json"))):
    runs = []
    for r in e["runs"]:
        first = read(r["judge"])
        last = read(r["reviewed"]) if r.get("reviewed") else first
        fees = None if r.get("judge_usd") is None and e["kind"] == "models" else round((r.get("judge_usd") or 0) + (r.get("review_usd") or 0), 2)
        runs.append({"first": first, "last": last, "usd": fees, "date": r.get("date"),
                     "failed": last["not_judged"] + (r.get("review_errors") or 0)})
    rows.append({"entrant": e, "runs": runs,
                 "sort": sum(r["last"]["usual"]["apart"] for r in runs) / len(runs)})
rows.sort(key=lambda r: -r["sort"])
if out:
    json.dump(rows, open(out, "w"), indent=1)

print("# Leaderboard\n")
print("Generated by `bench/score.py` from the runs in `bench/entrants.json`; [README.md](README.md) defines every column.")
print("A figure is what stood after review, with the first pass alone in brackets; two figures are the lowest and")
print("highest of the entrant's runs.\n")
print("| Entrant | Runs | Told apart, of 35 | New address: attacks, controls flagged, of 35 | Ordinary flagged, per 1,000 | Records or alerts it failed on | Fees a run |")
print("|---|---|---|---|---|---|---|")
for row in rows:
    e, runs = row["entrant"], row["runs"]
    col = lambda f, fmt="{}": span([f(r["last"]) for r in runs], fmt)
    was = lambda f, fmt="{}": "" if e["kind"] == "rules" else f" ({span([f(r['first']) for r in runs], fmt)})"
    per = lambda s: round(1000 * s["ordinary"] / s["ordinary_of"], 1)
    name = e["name"] if e["kind"] == "rules" else f"{e['name']}<br>{e['memory']}; {e['served']}"
    print(f"| {name} | {len(runs)} | **{col(lambda s: s['usual']['apart'])}**{was(lambda s: s['usual']['apart'])} "
          f"| {col(lambda s: s['away']['attacks'])}, {col(lambda s: s['away']['controls'])} "
          f"| {col(per)}{was(per)} | {span([r['failed'] for r in runs])} "
          f"| {'none' if e['kind'] == 'rules' else span([r['usd'] for r in runs], '${:.2f}')} |")
print("\nDevelopment set (not scored; the pipeline's brief was written against it): attacks caught of 36, harmless cases flagged of 12, after review.\n")
print("| Entrant | Caught, of 36 | Flagged, of 12 |\n|---|---|---|")
for row in rows:
    print(f"| {row['entrant']['name']} | {span([r['last']['dev_caught'] for r in row['runs']])} | {span([r['last']['dev_flagged'] for r in row['runs']])} |")
